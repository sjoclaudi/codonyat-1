"""Regression tests for --protein all and comma-separated lists.

Golden TSV/XML files under tests/data/ were generated by running
codonyat==1.1.0 from PyPI (not by hand):

    pip install 'codonyat==1.1.0'
    cd tests/data
    codonyat-runner hiv1_reads.sam hiv1_pol_ref.fasta hiv1_amps.tsv \\
        --protein all --csv-path hiv1_pol_all_v1.1.0.tsv --xml-path hiv1_pol_all_v1.1.0.xml
    codonyat-runner hiv1_reads.sam hiv1_pol_ref.fasta hiv1_amps.tsv \\
        --protein PR,RT,INT --csv-path hiv1_pol_PR_RT_INT_v1.1.0.tsv \\
        --xml-path hiv1_pol_PR_RT_INT_v1.1.0.xml
    codonyat-runner hiv1_reads.sam hiv1_pol_ref.fasta hiv1_amps.tsv \\
        --protein INT,PR --csv-path hiv1_pol_INT_PR_v1.1.0.tsv \\
        --xml-path hiv1_pol_INT_PR_v1.1.0.xml
"""

from __future__ import annotations

import filecmp
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

from aa_caller.app import (
    DEFAULT_ENTROPY_THRESHOLD,
    DEFAULT_RATIO_LOWER,
    DEFAULT_RATIO_UPPER,
    FullReference,
    SamContainer,
    parse_protein_spec,
    resolve_protein_targets,
    resolve_proteins,
    validate_reference_file,
)
from aa_caller.runner import call_variants

DATA = Path(__file__).parent / "data"
POL_FASTA = DATA / "hiv1_pol_ref.fasta"
SAM = DATA / "hiv1_reads.sam"
AMPS = DATA / "hiv1_amps.tsv"


def _run_pol(protein: str, tmp_path: Path) -> tuple[Path, Path]:
    """Run the current caller and emit TSV/XML with the same sample name as 1.1.0."""
    tmp_path.mkdir(parents=True, exist_ok=True)
    ref = FullReference(POL_FASTA)
    container = SamContainer(SAM, DEFAULT_RATIO_UPPER, DEFAULT_RATIO_LOWER, DEFAULT_ENTROPY_THRESHOLD)
    container.load()
    targets = resolve_protein_targets(protein, ref)
    names = [p.name for p in targets]
    container.calculate_for_proteins(targets, ref)
    rel_csv = tmp_path / "rel.tsv"
    rel_xml = tmp_path / "rel.xml"
    if len(names) == 1:
        container.write_csv("hiv1_reads.sam", ref, rel_csv, protein_name=names[0])
        container.write_xml("hiv1_reads.sam", ref, rel_xml)
    else:
        container.write_csv_proteins("hiv1_reads.sam", ref, rel_csv, names)
        container.write_xml_proteins("hiv1_reads.sam", ref, rel_xml, names)
    return rel_csv, rel_xml


class TestParseProteinSpec:
    def test_single_name(self) -> None:
        assert parse_protein_spec("RT") == ["RT"]

    def test_comma_list_keeps_order_drops_duplicates(self) -> None:
        assert parse_protein_spec("PR, RT, INT,PR") == ["PR", "RT", "INT"]

    def test_all(self) -> None:
        assert parse_protein_spec("all") == ["all"]
        assert parse_protein_spec("ALL") == ["ALL"]

    def test_all_cannot_mix(self) -> None:
        with pytest.raises(ValueError, match="cannot be combined"):
            parse_protein_spec("all,RT")

    def test_empty_rejected(self) -> None:
        with pytest.raises(ValueError, match="No protein selected"):
            parse_protein_spec(" , , ")

    def test_sequence_input(self) -> None:
        assert parse_protein_spec(["PR", "RT"]) == ["PR", "RT"]


class TestValidateProteinSelection:
    def test_all_does_not_require_all_in_header(self) -> None:
        validate_reference_file(POL_FASTA, protein_name="all")

    def test_comma_list_accepted(self) -> None:
        validate_reference_file(POL_FASTA, protein_name="PR,RT,INT")

    def test_comma_list_missing_name(self) -> None:
        with pytest.raises(ValueError, match="missing an ZZZ protein annotation"):
            validate_reference_file(POL_FASTA, protein_name="PR,ZZZ")


class TestResolveProteins:
    def test_all_uses_header_order(self) -> None:
        ref = FullReference(POL_FASTA)
        assert resolve_proteins("all", ref) == ["PR", "RT", "INT"]
        assert [p.name for p in resolve_protein_targets("all", ref)] == ["PR", "RT", "INT"]

    def test_comma_list_order(self) -> None:
        ref = FullReference(POL_FASTA)
        assert resolve_proteins("INT,PR", ref) == ["INT", "PR"]
        assert [p.name for p in resolve_protein_targets("INT,PR", ref)] == ["INT", "PR"]

    def test_missing_name(self) -> None:
        ref = FullReference(POL_FASTA)
        with pytest.raises(ValueError, match="not found"):
            resolve_proteins("PR,ZZZ", ref)


class TestOnePassMultiProtein:
    def test_single_pass_fills_all_proteins(self) -> None:
        ref = FullReference(POL_FASTA)
        container = SamContainer(SAM, DEFAULT_RATIO_UPPER, DEFAULT_RATIO_LOWER, DEFAULT_ENTROPY_THRESHOLD)
        container.load()
        container.calculate_variant_frequencies_multi(["PR", "RT", "INT"], ref)
        assert list(container.protein_variants) == ["PR", "RT", "INT"]
        assert sorted(container.protein_variants["PR"]) == [1, 4, 7]
        assert sorted(container.protein_variants["RT"]) == [10, 13, 16, 19]
        assert sorted(container.protein_variants["INT"]) == [22, 25, 28]
        # self.variants stays on the first requested protein (1.1.0 behaviour)
        assert sorted(container.variants) == [1, 4, 7]


class TestByteIdenticalToV110:
    def _assert_match(self, actual: Path, golden: Path) -> None:
        if not filecmp.cmp(actual, golden, shallow=False):
            print(f"\n=== Expected ({golden.name}) ===\n{golden.read_bytes()!r}")
            print(f"\n=== Actual ===\n{actual.read_bytes()!r}")
        assert filecmp.cmp(actual, golden, shallow=False), f"{actual.name} != {golden.name}"

    def _run_runner(self, tmp_path: Path, protein: str, monkeypatch: pytest.MonkeyPatch):
        for name in ("hiv1_reads.sam", "hiv1_pol_ref.fasta", "hiv1_amps.tsv"):
            (tmp_path / name).write_bytes((DATA / name).read_bytes())
        monkeypatch.chdir(tmp_path)
        return call_variants(
            sam_path="hiv1_reads.sam",
            reference_path="hiv1_pol_ref.fasta",
            amplicons_path="hiv1_amps.tsv",
            protein=protein,
        )

    def test_protein_all_matches_v1_1_0(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        result = self._run_runner(tmp_path, "all", monkeypatch)
        self._assert_match(result.csv_path, DATA / "hiv1_pol_all_v1.1.0.tsv")
        self._assert_match(result.xml_path, DATA / "hiv1_pol_all_v1.1.0.xml")

    def test_protein_comma_list_matches_v1_1_0(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        result = self._run_runner(tmp_path, "PR,RT,INT", monkeypatch)
        self._assert_match(result.csv_path, DATA / "hiv1_pol_PR_RT_INT_v1.1.0.tsv")
        self._assert_match(result.xml_path, DATA / "hiv1_pol_PR_RT_INT_v1.1.0.xml")

    def test_protein_comma_list_custom_order_matches_v1_1_0(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        result = self._run_runner(tmp_path, "INT,PR", monkeypatch)
        self._assert_match(result.csv_path, DATA / "hiv1_pol_INT_PR_v1.1.0.tsv")
        self._assert_match(result.xml_path, DATA / "hiv1_pol_INT_PR_v1.1.0.xml")

    def test_protein_all_container_path_matches_v1_1_0(self, tmp_path: Path) -> None:
        tsv, xml = _run_pol("all", tmp_path)
        self._assert_match(tsv, DATA / "hiv1_pol_all_v1.1.0.tsv")
        self._assert_match(xml, DATA / "hiv1_pol_all_v1.1.0.xml")

    def test_all_and_header_order_list_are_identical(self, tmp_path: Path) -> None:
        all_tsv, all_xml = _run_pol("all", tmp_path / "all")
        list_tsv, list_xml = _run_pol("PR,RT,INT", tmp_path / "list")
        assert all_tsv.read_bytes() == list_tsv.read_bytes()
        assert all_xml.read_bytes() == list_xml.read_bytes()

    def test_single_protein_xml_has_no_protein_wrapper(self, tmp_path: Path) -> None:
        tsv, xml = _run_pol("RT", tmp_path)
        root = ET.parse(xml).getroot()
        assert root.findall("Protein") == []
        assert len(root.findall("Position")) == 4
        rows = tsv.read_text().splitlines()
        assert rows[0].startswith("FILE\tREFERENCE\tPROTEIN")
        assert all("\tRT\t" in row for row in rows[1:])

    def test_multi_protein_xml_has_wrappers(self, tmp_path: Path) -> None:
        _tsv, xml = _run_pol("all", tmp_path)
        root = ET.parse(xml).getroot()
        proteins = root.findall("Protein")
        assert [p.get("name") for p in proteins] == ["PR", "RT", "INT"]
        assert root.findall("Position") == []
        assert len(proteins[0].findall("Position")) == 3


class TestCallVariantsProteinAll:
    def test_call_variants_all_writes_wrappers(self, tmp_path: Path) -> None:
        csv_out = tmp_path / "out.tsv"
        xml_out = tmp_path / "out.xml"
        result = call_variants(
            sam_path=SAM,
            reference_path=POL_FASTA,
            amplicons_path=AMPS,
            protein="all",
            csv_path=csv_out,
            xml_path=xml_out,
        )
        assert result.proteins == ["PR", "RT", "INT"]
        root = ET.parse(xml_out).getroot()
        assert [p.get("name") for p in root.findall("Protein")] == ["PR", "RT", "INT"]
        header = csv_out.read_text().splitlines()[0]
        assert "RECORD" not in header.split("\t")


class TestMultiRecordAll:
    def test_all_on_multi_record_keeps_record_column(self, tmp_path: Path) -> None:
        fasta_path = tmp_path / "ref.fasta"
        fasta_path.write_text(
            ">Seg1 GeneA(ProteinA):1-30\nATGCCCTTTAAAGGGCCCAAATTTGGGCCC\n"
            ">Seg2 GeneB(ProteinB):1-30\nTTTGGGCCCAAAGGGTTTACGTCGATCGAT\n"
        )
        sam_path = tmp_path / "reads.sam"
        sam_path.write_text(
            "@HD\tVN:1.6\n@SQ\tSN:Seg1\tLN:30\n@SQ\tSN:Seg2\tLN:30\n"
            "read1\t0\tSeg1\t1\t30\t30M\t*\t0\t0\tATGCCCTTTAAAGGGCCCAAATTTGGGCCC\tIIIIIIIIIIIIIIIIIIIIIIIIIIIIII\n"
            "read2\t0\tSeg2\t1\t30\t30M\t*\t0\t0\tTTTGGGCCCAAAGGGTTTACGTCGATCGAT\tIIIIIIIIIIIIIIIIIIIIIIIIIIIIII\n"
        )
        amp_path = tmp_path / "amps.tsv"
        amp_path.write_text(
            "label\tprotein\treference\t5p\t3p\tstart\tend\n"
            "Amp_1\tGeneA\tSeg1\tATG\tCCC\t1\t30\n"
            "Amp_2\tGeneB\tSeg2\tTTT\tGAT\t1\t30\n"
        )
        result = call_variants(
            sam_path=sam_path,
            reference_path=fasta_path,
            amplicons_path=amp_path,
            protein="all",
            csv_path=tmp_path / "out.tsv",
            xml_path=tmp_path / "out.xml",
        )
        assert result.proteins == ["GeneA", "GeneB"]
        text = (tmp_path / "out.tsv").read_text()
        header = text.splitlines()[0].split("\t")
        assert header == [
            "FILE",
            "REFERENCE",
            "RECORD",
            "PROTEIN",
            "VARIANT",
            "POSITION",
            "FREQ",
            "FWCOV",
            "RVCOV",
            "TOTALCOV",
            "RATIO",
        ]
        assert "GeneA" in text and "GeneB" in text
        root = ET.parse(tmp_path / "out.xml").getroot()
        assert [p.get("name") for p in root.findall("Protein")] == ["GeneA", "GeneB"]
